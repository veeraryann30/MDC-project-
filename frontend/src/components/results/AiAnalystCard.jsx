import React from 'react';
import { motion, useReducedMotion } from 'framer-motion';
import { Sparkles, Bot, ListChecks, Crosshair, AlertCircle } from 'lucide-react';

const EASE = [0.16, 1, 0.3, 1];

/**
 * AI Security Analyst. Shows the explanation the backend produced from the scan evidence and says
 * plainly who wrote it: Groq (Llama) or the deterministic rule-based fallback. It never alters the score.
 */
export default function AiAnalystCard({ analysis }) {
  const reduced = useReducedMotion();
  if (!analysis) return null;

  const isAi = String(analysis.generated_by || '').startsWith('groq:');
  const model = isAi ? analysis.generated_by.slice(5) : null;

  return (
    <motion.section
      aria-labelledby="ai-analyst-title"
      initial={reduced ? false : { opacity: 0, y: 14 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.6, ease: EASE }}
      className="relative overflow-hidden rounded-2xl border border-[#DBEAFE] bg-white p-5 shadow-sm sm:p-6"
    >
      <div className="flex flex-wrap items-center justify-between gap-3">
        <h3 id="ai-analyst-title" className="flex items-center gap-2 font-mono text-sm font-bold uppercase tracking-wider text-[#111827]">
          {isAi ? <Sparkles className="h-4 w-4 text-[#2563EB]" /> : <Bot className="h-4 w-4 text-[#64748B]" />}
          AI Security Analyst
        </h3>
        <span
          className={`rounded-full border px-2.5 py-1 text-[10px] font-bold uppercase tracking-wider ${
            isAi ? 'border-[#BFDBFE] bg-white text-[#2563EB]' : 'border-[#E2E8F0] bg-white text-[#64748B]'
          }`}
          title={isAi ? 'Written by a language model from the scan evidence' : 'Generated by fixed rules from the scan evidence'}
        >
          {isAi ? `Groq · ${model}` : 'Rule-based explanation'}
        </span>
      </div>

      {analysis.note && (
        <p className="mt-3 flex items-start gap-2 rounded-lg border border-[#E2E8F0] bg-white px-3 py-2 text-[12px] text-[#64748B]">
          <AlertCircle className="mt-0.5 h-3.5 w-3.5 shrink-0 text-[#94A3B8]" />{analysis.note}
        </p>
      )}

      <h4 className="mt-4 text-lg font-bold leading-snug text-[#111827]">{analysis.headline}</h4>
      <p className="mt-2 text-[13.5px] leading-relaxed text-[#475569]">{analysis.summary}</p>

      <div className="mt-5 grid grid-cols-1 gap-4 md:grid-cols-2">
        {analysis.key_findings?.length > 0 && (
          <div className="rounded-xl border border-[#E2E8F0] bg-white p-4">
            <h5 className="flex items-center gap-1.5 text-[11px] font-bold uppercase tracking-wider text-[#64748B]"><Crosshair className="h-3.5 w-3.5" /> What the evidence shows</h5>
            <ul className="mt-2 space-y-2 text-[12.5px] leading-relaxed text-[#475569]">
              {analysis.key_findings.map((f) => (
                <li key={f} className="flex gap-2"><span className="mt-[7px] h-1.5 w-1.5 shrink-0 rounded-full bg-[#2563EB]" />{f}</li>
              ))}
            </ul>
            {analysis.phishing_techniques?.length > 0 && (
              <div className="mt-3 flex flex-wrap gap-1.5 border-t border-[#E2E8F0] pt-3">
                {analysis.phishing_techniques.map((t) => (
                  <span key={t} className="rounded-md border border-[#FDE68A] bg-[#FFFBEB] px-2 py-0.5 text-[11px] font-medium text-[#D97706]">{t}</span>
                ))}
              </div>
            )}
          </div>
        )}
        {analysis.recommendations?.length > 0 && (
          <div className="rounded-xl border border-[#E2E8F0] bg-white p-4">
            <h5 className="flex items-center gap-1.5 text-[11px] font-bold uppercase tracking-wider text-[#64748B]"><ListChecks className="h-3.5 w-3.5" /> What to do</h5>
            <ol className="mt-2 space-y-2 text-[12.5px] leading-relaxed text-[#475569]">
              {analysis.recommendations.map((r, i) => (
                <li key={r} className="flex gap-2.5">
                  <span className="flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-[#EFF6FF] font-mono text-[10px] font-bold text-[#2563EB]">{i + 1}</span>{r}
                </li>
              ))}
            </ol>
          </div>
        )}
      </div>

      {analysis.limitations && (
        <p className="mt-4 text-[11.5px] leading-relaxed text-[#94A3B8]"><strong className="font-semibold text-[#64748B]">Limits: </strong>{analysis.limitations}</p>
      )}
    </motion.section>
  );
}
